/**
 * custom-SCADA: import of Siemens S7 variables (TIA Portal exports) as FUXA S7 tags
 * - PLC tag table (CSV): global tags with logical address (%MW10, %M0.1, %I0.0, %QW2...)
 * - source of a non optimized DB (.db, "Generate source from blocks"): offsets computed with the S7 rules
 */

export interface S7ImportVariable {
    name: string;
    /** FUXA S7 tag type: Bool, Byte, Int, Word, DInt, DWord, Real */
    type: string;
    /** FUXA S7 address: MW10, M0.1, I0.0, DB1.DBX0.0, DB1.DBW2, DB1.DBD4... */
    address: string;
    /** not empty when the variable cannot be imported (type not supported...) */
    error?: string;
}

export interface S7ImportResult {
    variables: S7ImportVariable[];
    /** global problem (file format, optimized DB...) */
    error?: string;
}

/** TIA data types → FUXA S7 tag type and size in bytes (0 = bit) */
const S7_TYPES: { [tiaType: string]: { type: string; size: number } } = {
    BOOL: { type: 'Bool', size: 0 },
    BYTE: { type: 'Byte', size: 1 },
    USINT: { type: 'Byte', size: 1 },
    CHAR: { type: 'Byte', size: 1 },
    INT: { type: 'Int', size: 2 },
    WORD: { type: 'Word', size: 2 },
    UINT: { type: 'Word', size: 2 },
    DINT: { type: 'DInt', size: 4 },
    DWORD: { type: 'DWord', size: 4 },
    UDINT: { type: 'DWord', size: 4 },
    REAL: { type: 'Real', size: 4 },
};

/** size in bytes of the types that are skipped but must move the offset */
const S7_SKIPPED_SIZES: { [tiaType: string]: number } = {
    SINT: 1, TIME: 4, DATE: 2, TIME_OF_DAY: 4, TOD: 4, S5TIME: 2, LREAL: 8, LINT: 8, ULINT: 8, LWORD: 8, WCHAR: 2
};

export class S7ImportHelper {

    /**
     * PLC tag table exported from TIA Portal and saved as CSV (separator ; , or tab)
     * the columns are found by name: Name / Nom, Data Type / Type de données, Logical Address / Adresse logique
     */
    static parseTagTableCsv(text: string): S7ImportResult {
        const lines = (text || '').replace(/^﻿/, '').split(/\r?\n/).filter(l => l.trim());
        if (lines.length < 2) {
            return { variables: [], error: 'empty' };
        }
        const separator = [';', '\t', ','].map(s => ({ s, n: lines[0].split(s).length })).sort((a, b) => b.n - a.n)[0].s;
        const header = S7ImportHelper.splitCsvLine(lines[0], separator).map(h => h.trim().toLowerCase());
        const col = (...names: string[]) => header.findIndex(h => names.some(n => h === n || h.startsWith(n)));
        const iName = col('name', 'nom');
        const iType = col('data type', 'type de données', 'type de donnees', 'datatype', 'type');
        const iAddress = col('logical address', 'adresse logique', 'address', 'adresse');
        if (iName < 0 || iType < 0 || iAddress < 0) {
            return { variables: [], error: 'columns' };
        }
        const variables: S7ImportVariable[] = [];
        for (const line of lines.slice(1)) {
            const cells = S7ImportHelper.splitCsvLine(line, separator);
            const name = (cells[iName] || '').trim();
            if (!name) {
                continue;
            }
            const tiaType = (cells[iType] || '').trim().toUpperCase();
            const rawAddress = (cells[iAddress] || '').trim();
            const known = S7_TYPES[tiaType];
            const address = S7ImportHelper.convertLogicalAddress(rawAddress);
            if (!known) {
                variables.push({ name, type: tiaType, address: rawAddress, error: 'type' });
            } else if (!address) {
                variables.push({ name, type: known.type, address: rawAddress, error: 'address' });
            } else {
                variables.push({ name, type: known.type, address });
            }
        }
        return { variables };
    }

    /** %MW10 → MW10, %M0.1 → M0.1, %I0.0 → I0.0, %QD4 → QD4 (I/Q/M areas, also German E/A) */
    static convertLogicalAddress(address: string): string | null {
        const a = (address || '').trim().replace(/^%/, '').toUpperCase().replace(/\s+/g, '');
        if (/^[IEQAM]\d+\.[0-7]$/.test(a) || /^[IEQAM][BWD]\d+$/.test(a)) {
            return a;
        }
        return null;
    }

    /**
     * source of a DB generated by TIA Portal ("Generate source from blocks")
     * the DB must not be optimized: S7_Optimized_Access := 'FALSE'
     */
    static parseDbSource(text: string, dbNumber: number): S7ImportResult {
        let src = (text || '').replace(/^﻿/, '');
        if (!/DATA_BLOCK/i.test(src)) {
            return { variables: [], error: 'notdb' };
        }
        if (/S7_Optimized_Access\s*:=\s*'TRUE'/i.test(src)) {
            return { variables: [], error: 'optimized' };
        }
        // remove comments, attributes, initial values and the part after BEGIN
        src = src.replace(/\(\*[\s\S]*?\*\)/g, ' ').replace(/\/\/.*$/gm, ' ');
        const begin = src.search(/\bBEGIN\b/i);
        if (begin >= 0) {
            src = src.substring(0, begin);
        }
        const structStart = src.search(/\bSTRUCT\b/i);
        if (structStart < 0) {
            return { variables: [], error: 'notdb' };
        }
        src = src.substring(structStart).replace(/\{[^}]*\}/g, ' ');
        const tokens = src.split(';').map(t => t.replace(/\s+/g, ' ').replace(/:=.*$/, '').trim()).filter(t => t);
        const state = { byte: 0, bit: 0 };
        const variables: S7ImportVariable[] = [];
        const path: string[] = [];
        for (let raw of tokens) {
            // a token can start with STRUCT (first one) or contain "name : Struct"
            raw = raw.replace(/^STRUCT\b/i, '').trim();
            if (/^END_STRUCT/i.test(raw)) {
                S7ImportHelper.alignEven(state);
                path.pop();
                raw = raw.replace(/^END_STRUCT/i, '').trim();
                if (!raw) {
                    continue;
                }
            }
            const m = raw.match(/^"?([^":]+?)"?\s*:\s*(.+)$/);
            if (!m) {
                continue;
            }
            const name = m[1].trim();
            let type = m[2].trim();
            const structMatch = type.match(/^Struct\b\s*(.*)$/i);
            if (structMatch) {
                S7ImportHelper.alignEven(state);
                path.push(name);
                // first member of the struct can be on the same token
                const rest = structMatch[1].trim();
                if (rest) {
                    S7ImportHelper.addMember(rest, path, state, dbNumber, variables);
                }
                continue;
            }
            S7ImportHelper.addMember(`${name} : ${type}`, path, state, dbNumber, variables);
        }
        return { variables };
    }

    private static addMember(decl: string, path: string[], state: { byte: number; bit: number }, dbNumber: number, variables: S7ImportVariable[]) {
        const m = decl.match(/^"?([^":]+?)"?\s*:\s*(.+)$/);
        if (!m) {
            return;
        }
        const name = [...path, m[1].trim()].join('.');
        const type = m[2].trim();
        const arrayMatch = type.match(/^Array\s*\[\s*(-?\d+)\s*\.\.\s*(-?\d+)\s*\]\s*of\s+(.+)$/i);
        if (arrayMatch) {
            const from = parseInt(arrayMatch[1], 10), to = parseInt(arrayMatch[2], 10);
            const elemType = arrayMatch[3].trim();
            S7ImportHelper.alignEven(state);
            for (let i = from; i <= to; i++) {
                S7ImportHelper.addSimple(`${name}[${i}]`, elemType, state, dbNumber, variables, true);
            }
            S7ImportHelper.alignEven(state);
            return;
        }
        S7ImportHelper.addSimple(name, type, state, dbNumber, variables, false);
    }

    private static addSimple(name: string, tiaTypeRaw: string, state: { byte: number; bit: number }, dbNumber: number,
                             variables: S7ImportVariable[], inArray: boolean) {
        const tiaType = tiaTypeRaw.toUpperCase();
        const known = S7_TYPES[tiaType];
        if (known && known.size === 0) {
            variables.push({ name, type: known.type, address: `DB${dbNumber}.DBX${state.byte}.${state.bit}` });
            state.bit++;
            if (state.bit === 8) {
                state.byte++;
                state.bit = 0;
            }
            return;
        }
        // any other type starts on a new byte, types of 2 bytes or more on an even byte
        if (state.bit > 0) {
            state.byte++;
            state.bit = 0;
        }
        const stringMatch = tiaType.match(/^STRING(\s*\[\s*(\d+)\s*\])?$/);
        const size = known ? known.size : stringMatch ? (stringMatch[2] ? parseInt(stringMatch[2], 10) : 254) + 2 : S7_SKIPPED_SIZES[tiaType];
        if (!size) {
            variables.push({ name, type: tiaTypeRaw, address: '', error: 'type' });
            return;
        }
        if (size >= 2 && !inArray) {
            S7ImportHelper.alignEven(state);
        } else if (size >= 2 && state.byte % 2) {
            state.byte++;
        }
        if (known) {
            const area = known.size === 1 ? 'DBB' : known.size === 2 ? 'DBW' : 'DBD';
            variables.push({ name, type: known.type, address: `DB${dbNumber}.${area}${state.byte}` });
        } else {
            variables.push({ name, type: tiaTypeRaw, address: '', error: 'type' });
        }
        state.byte += size;
    }

    private static alignEven(state: { byte: number; bit: number }) {
        if (state.bit > 0) {
            state.byte++;
            state.bit = 0;
        }
        if (state.byte % 2) {
            state.byte++;
        }
    }

    private static splitCsvLine(line: string, separator: string): string[] {
        const result: string[] = [];
        let current = '', quoted = false;
        for (let i = 0; i < line.length; i++) {
            const c = line[i];
            if (c === '"') {
                if (quoted && line[i + 1] === '"') {
                    current += '"';
                    i++;
                } else {
                    quoted = !quoted;
                }
            } else if (c === separator && !quoted) {
                result.push(current);
                current = '';
            } else {
                current += c;
            }
        }
        result.push(current);
        return result;
    }
}
